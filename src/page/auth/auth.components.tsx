/* ── GRADIENT CANVAS BACKGROUND ── */
const BLOB_CONFIG = [
  { xRatio: 0.2, yRatio: 0.3, r: 280, dx: 0.25, dy: 0.18, color: 'rgba(200,241,53,', alpha: 0.07 },
  { xRatio: 0.8, yRatio: 0.6, r: 320, dx: -0.2, dy: 0.22, color: 'rgba(74,158,255,', alpha: 0.06 },
  { xRatio: 0.5, yRatio: 0.8, r: 240, dx: 0.15, dy: -0.25, color: 'rgba(200,241,53,', alpha: 0.04 },
  { xRatio: 0.1, yRatio: 0.9, r: 200, dx: 0.3, dy: -0.15, color: 'rgba(245,166,35,', alpha: 0.05 },
]

export function GradientBackground() {
  const canvasRef = useRef<HTMLCanvasElement>(null)

  useEffect(() => {
    if (!canvasRef.current) return
    return initCanvasBlobs(canvasRef.current, BLOB_CONFIG)
  }, [])

  return (
    <>
      <canvas ref={canvasRef} className={s.tbCanvas} />
      <div className={s.tbNoise} style={{ backgroundImage: NOISE_SVG }} />
    </>
  )
}

